const mk = (
  id: string,
  admissionNo: string,
  firstName: string,
  lastName: string,
  className: string,
  boarding: Student["boarding"],
  guardianId: string,
  billed: number,
  paid: number,
): Student => {
  const guardian = GUARDIANS[guardianId];
  const outstanding = Math.max(0, billed - paid);
  const overdue =
    outstanding > 0
      ? Math.round(outstanding * (0.35 + (admissionNo.charCodeAt(5) % 5) * 0.1))
      : 0;
  const status: Student["status"] =
    outstanding === 0
      ? "PAID"
      : overdue > 0
        ? "OVERDUE"
        : paid > 0
          ? "PARTIALLY_PAID"
          : "UNPAID";
  return {
    id,
    admissionNo,
    firstName,
    lastName,
    fullName: `${firstName} ${lastName}`,
    classId: `c_${className.replace(/\s+/g, "").toLowerCase()}`,
    className,
    boarding,
    guardianId,
    guardian,
    status,
    billed,
    paid,
    outstanding,
    overdue,
    photoInitials: `${firstName[0]}${lastName[0]}`,
  };
};

