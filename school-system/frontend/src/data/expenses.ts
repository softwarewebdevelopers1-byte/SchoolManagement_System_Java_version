export const CASHBOOK: CashbookEntry[] = (() => {
  const entries: Omit<CashbookEntry, "balance">[] = [];
  let i = 0;
  for (const e of EXPENSES) {
    entries.push({
      id: `cb_${pad(++i, 5)}`,
      date: e.date,
      reference: e.number,
      description: e.description,
      account: "Operating Account",
      debit: 0,
      credit: e.amount,
    });
  }
  for (const p of [
    "pay_00001",
    "pay_00002",
    "pay_00003",
    "pay_00004",
    "pay_00005",
  ]) {
    entries.push({
      id: `cb_${pad(++i, 5)}`,
      date: d(10 + i),
      reference: p,
      description: "Fee payment received",
      account: "Operating Account",
      debit: 45000,
      credit: 0,
    });
  }
  entries.sort((a, b) => a.date.localeCompare(b.date));
  let bal = 1_500_000;
  return entries.map((e) => {
    bal += e.debit - e.credit;
    return { ...e, balance: bal };
  });
})();

